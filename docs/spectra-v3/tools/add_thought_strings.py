def esc(v):
    return v.replace('&', '&amp;').replace('<', '&lt;').replace("'", "\\'").replace('"', '\\"')

base = pathlib.Path('src/android/app/src/main/res')
n = 0
for loc, vals in T.items():
    assert len(vals) == len(K), loc
    p = base / ('values' if not loc else f'values-{loc}') / 'strings.xml'
    s = p.read_text()
    add = ''.join(f'    <string name="{k}">{esc(v)}</string>\n'
                  for k, v in zip(K, vals) if f'name="{k}"' not in s)
    if add:
        i = s.rindex('</resources>')
        p.write_text(s[:i] + '    <!-- [T-spectra-v4-thought] -->\n' + add + s[i:])
        n += 1
print('locales patched:', n, '/', len(T))
